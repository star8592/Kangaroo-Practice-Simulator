import assert from "node:assert/strict";
import {practiceRow,practiceSummary} from "../src/lib/wuhan-practice-summary";
const rev="a".repeat(64);
const candidate=(state:string,practice_content:unknown,revision=rev)=>({kind:"answer",state,candidate:{status:state,official_score:false,reference_content_score:null,human_review_required:true,machine_rule_revision:revision,practice_content}});
const yes=candidate("reference_match",{earned:1,possible:1,basis:"automatic_content_match"});
const no=candidate("known_mismatch",{earned:0,possible:1,basis:"automatic_known_mismatch"});
const silence=candidate("unanswered",{earned:0,possible:1,basis:"no_answer_audio"});
const unknown=candidate("needs_review",null);
const blank={kind:"answer",state:"not_submitted",candidate:null};
const all=[yes,no,silence,unknown,blank,yes,blank,{kind:"read",state:"reference_text_matched",candidate:yes.candidate},{kind:"retell",state:"partial_reference",candidate:yes.candidate}];
const s=practiceSummary(all);
assert.equal(s.total,7);assert.equal(s.decided,3);assert.deepEqual(s.points,{earned:2,possible:3});
assert.deepEqual(s.counts,{match:2,mismatch:1,silence:1,blank:2,uncertain:1,legacy:0,invalid:0});
assert.equal(practiceSummary(Array(7).fill(blank)).points,null);
assert.equal(practiceSummary(Array(7).fill(silence)).points,null);
assert.equal(practiceSummary(Array(7).fill(unknown)).points,null);
assert.equal(practiceSummary([yes]).points,null);
assert.equal(practiceRow(candidate("needs_review",{earned:1,possible:1,basis:"automatic_content_match"}))?.kind,"invalid");
assert.equal(practiceRow(candidate("reference_match",{earned:0,possible:1,basis:"automatic_content_match"}))?.kind,"invalid");
assert.equal(practiceRow(candidate("reference_match",{earned:1,possible:1,basis:"automatic_content_match"},"unknown"))?.kind,"invalid");
assert.equal(practiceRow({...yes,candidate:{...yes.candidate,official_score:true}})?.kind,"invalid");
assert.equal(practiceRow({...yes,candidate:{...yes.candidate,reference_content_score:100}})?.kind,"invalid");
assert.equal(practiceRow({...yes,candidate:{...yes.candidate,status:"known_mismatch"}})?.kind,"invalid");
assert.equal(practiceRow({...blank,candidate:yes.candidate})?.kind,"invalid");
const mixed=practiceSummary([yes,no,silence,unknown,blank,candidate("reference_match",{earned:1,possible:1,basis:"automatic_content_match"},"b".repeat(64)),blank]);
assert.equal(mixed.mixedRevision,true);assert.equal(mixed.points,null);
const legacy={...yes,candidate:{...yes.candidate,machine_rule_revision:undefined,practice_content:undefined}};
assert.equal(practiceRow(legacy)?.kind,"legacy");
assert.equal(practiceSummary([yes,no,silence,unknown,blank,legacy,blank]).points,null);
console.log("WUHAN_PRACTICE_SUMMARY_PASS separated denominator; no silence or uncertainty inflation; malformed and mixed revisions rejected");
