import assert from "node:assert/strict";
import {randomBytes} from "node:crypto";
import {deriveVoucherCode,voucherLookupDigest,voucherCodeMatches,planVoucherClaim,planVoucherRefund} from "../src/lib/commerce/voucher-contract.mjs";
const issue=randomBytes(32),lookup=randomBytes(32);
const unit={channel:"xiaohongshu",merchantId:"sandbox-shop",orderLineId:"sandbox-line",unitIndex:0};
const a=deriveVoucherCode(unit,issue);
assert.equal(a,deriveVoucherCode(unit,issue));
for(const u of [{...unit,unitIndex:1},{...unit,channel:"douyin"},{...unit,channel:"xianyu"},{...unit,merchantId:"other"},{...unit,orderLineId:"other"}])assert.notEqual(a,deriveVoucherCode(u,issue));
assert.notEqual(a,deriveVoucherCode(unit,issue,2));
assert.notEqual(a,deriveVoucherCode(unit,randomBytes(32)));
assert.throws(()=>deriveVoucherCode(unit,Buffer.alloc(8)));
assert.throws(()=>deriveVoucherCode({...unit,channel:"unknown"},issue));
const digest=voucherLookupDigest(a,lookup);
assert(voucherCodeMatches(a,digest,lookup));
assert(!voucherCodeMatches(a,digest,issue));
assert(!voucherCodeMatches("bad",digest,lookup));
assert(!voucherCodeMatches(deriveVoucherCode({...unit,unitIndex:1},issue),digest,lookup));
const now=100,base={state:"issued",orderState:"paid",ownerId:null,expiresAt:200};
assert.equal(planVoucherClaim(base,"par_test",now),"claim_and_grant_atomically");
for(const state of ["pending","refunded","closed"])assert.throws(()=>planVoucherClaim({...base,orderState:state},"par_test",now));
assert.throws(()=>planVoucherClaim(base,"par_test",200));
assert.throws(()=>planVoucherClaim({...base,state:"revoked"},"par_test",now));
const claimed={...base,state:"claimed",ownerId:"par_test"};
assert.equal(planVoucherClaim(claimed,"par_test",now),"already_claimed");
assert.throws(()=>planVoucherClaim(claimed,"par_other",now));
assert.equal(planVoucherRefund("issued"),"revoke_unclaimed");
assert.equal(planVoucherRefund("claimed"),"revoke_grant_preserve_history");
assert.equal(planVoucherRefund("revoked"),"already_revoked");
assert.throws(()=>planVoucherRefund("invalid"));
console.log("VOUCHER_CONTRACT=PASS (isolated pure functions; no live issuance)");
